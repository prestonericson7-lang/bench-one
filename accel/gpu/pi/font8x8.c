static const uint8_t *glyph(unsigned char c)
{
    if (c < 0x20 || c > 0x7E)
        c = '?';
    return font8x8_basic[c];
}

int font_text_w(const char *s, int scale)
{
    int w = 0, cur = 0;
    for (; *s; s++) {
        if (*s == '\n') {
            cur = 0;
            continue;
        }
        cur += 8 * scale;
        if (cur > w)
            w = cur;
    }
    return w;
}

int font_text_h(const char *s, int scale)
{
    int lines = *s ? 1 : 0;
    for (; *s; s++)
        if (*s == '\n' && s[1])
            lines++;
    return lines * 8 * scale;
}

static void put(uint16_t *buf, int bw, int bh, int x, int y, int scale, uint16_t c)
{
    int i, j;
    for (j = 0; j < scale; j++) {
        int yy = y + j;
        if (yy < 0 || yy >= bh)
            continue;
        for (i = 0; i < scale; i++) {
            int xx = x + i;
            if (xx >= 0 && xx < bw)
                buf[(long)yy * bw + xx] = c;
        }
    }
}

static int bit_at(const uint8_t *g, int col, int row)
{
    if (col < 0 || col > 7 || row < 0 || row > 7)
        return 0;
    return (g[row] >> col) & 1;
}

void font_draw(uint16_t *buf, int bw, int bh, int x, int y, const char *s, int scale, uint16_t fg, uint16_t bg,
               int transparent_bg)
{
    int cx = x, cy = y;
    if (scale < 1)
        scale = 1;
    for (; *s; s++) {
        const uint8_t *g;
        int r, c;
        if (*s == '\n') {
            cx = x;
            cy += 8 * scale;
            continue;
        }
        g = glyph((unsigned char)*s);
        for (r = 0; r < 8; r++)
            for (c = 0; c < 8; c++) {
                if (bit_at(g, c, r))
                    put(buf, bw, bh, cx + c * scale, cy + r * scale, scale, fg);
                else if (!transparent_bg)
                    put(buf, bw, bh, cx + c * scale, cy + r * scale, scale, bg);
            }
        cx += 8 * scale;
    }
}

void font_draw_outlined(uint16_t *buf, int bw, int bh, int x, int y, const char *s, int scale, uint16_t fg,
                        uint16_t outline)
{
    int cx = x, cy = y;
    if (scale < 1)
        scale = 1;
    for (; *s; s++) {
        const uint8_t *g;
        int r, c;
        if (*s == '\n') {
            cx = x;
            cy += 8 * scale;
            continue;
        }
        g = glyph((unsigned char)*s);
        /* outline: every non-glyph cell next to a glyph cell (8-neighbourhood), incl. one cell
         * beyond the 8x8 box */
        for (r = -1; r <= 8; r++)
            for (c = -1; c <= 8; c++) {
                int dr, dc, near = 0;
                if (bit_at(g, c, r))
                    continue;
                for (dr = -1; dr <= 1 && !near; dr++)
                    for (dc = -1; dc <= 1; dc++)
                        if (bit_at(g, c + dc, r + dr)) {
                            near = 1;
                            break;
                        }
                if (near)
                    put(buf, bw, bh, cx + c * scale, cy + r * scale, scale, outline);
            }
        for (r = 0; r < 8; r++)
            for (c = 0; c < 8; c++)
                if (bit_at(g, c, r))
                    put(buf, bw, bh, cx + c * scale, cy + r * scale, scale, fg);
        cx += 8 * scale;
    }
}
