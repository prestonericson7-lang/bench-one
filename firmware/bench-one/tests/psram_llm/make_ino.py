#!/usr/bin/env python3
"""Regenerate psram_llm_board.cpp: psram_worker's bus layer copied line for line, then this sketch's own part.

Run from this folder after editing psram_llm_board.inc, or after psram_worker's bus layer changes:
    python make_ino.py
The line ranges are asserted against their first lines, so a shifted psram_worker fails loudly instead of
copying the wrong code."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
W = open(os.path.join(HERE, "..", "psram_worker", "psram_worker.ino"), encoding="utf-8").read().split("\n")
def L(a, b): return W[a - 1:b]
assert W[46 - 1].startswith("#include <Arduino.h>"), W[45]
assert W[88 - 1].startswith("template <int S> static inline void addr_out"), W[87]
assert W[183 - 1].startswith("#define PIN_DEC"), W[182]
assert W[660 - 1].strip().startswith("return id[0] == 0x0D"), W[659]
assert W[661 - 1].strip() == "}", W[660]
assert W[822 - 1].startswith("static uint8_t g_tag;"), W[821]
assert W[901 - 1].startswith("static inline uint8_t pat"), W[900]
HEAD = """/* ===========================================================================================
 *  psram_llm v9 -- Qwen2.5-Coder-3B (3,085,938,688 parameters) on a Teensy 4.1
 *
 *  GENERATED by make_ino.py from psram_worker.ino and psram_llm_board.inc -- edit those, not this.
 *  A .cpp rather than the .ino: the Arduino builder writes a prototype for every function in an .ino,
 *  and for the bus layer's templates it writes non-template ones that are never defined.
 *
 *  BOARD    Teensy 4.1 + ESP-PSRAM64H banks (CS0/CS1 on the pads, Y0-Y7 behind a 74LVC138A) + the
 *           built-in microSD holding qwen3b.gguf (Ollama blob sha256-4a188102..., 1,929,903,072 bytes)
 *  WHAT     the whole model stays on the card (weights, norms and biases every token; the tokenizer's
 *           tables in qwen3b.tok beside it); the PSRAM is the attention cache and nothing else; the
 *           Teensy's own RAM runs the arithmetic, shared/tl_core.c, proven on the PC to
 *           produce model_q.c's logits bit for bit (tests/tl_host.c against tests/tl_ref.c)
 *  BUILD    build.bat (refreshes the shared copies, then arduino-cli). Serial 115200.
 *
 *  Lines 1-94 and 183-661 of psram_worker.ino and its test pattern follow VERBATIM, because a no-op count
 *  is a timing specification for one exact instruction sequence. Qualification then runs again on THIS
 *  binary at every boot rather than trusting numbers measured on another one.
 * ======================================================================================== */
#include <Arduino.h>
#include <SdFat.h>
#include <stdarg.h>
#include "tl_core.h"
#include "tl_plat.h"
#include "gguf.h"
#include "psram_llm.h"
"""
body = open(os.path.join(HERE, "psram_llm_board.inc"), encoding="utf-8").read()
out = [HEAD, "\n".join(L(1, 94)), "", "\n".join(L(183, 661)), "", W[822 - 1], "", "\n".join(L(901, 904)), "", body]
open(os.path.join(HERE, "psram_llm_board.cpp"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("psram_llm_board.cpp written")
